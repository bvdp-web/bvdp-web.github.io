  // Generate the Dutch calendar date in YYYY-MM-DD format.
  function localDateKey(date = new Date()) {
    const parts = new Intl.DateTimeFormat("en-GB", {
      timeZone: "Europe/Amsterdam",
      year: "numeric",
      month: "2-digit",
      day: "2-digit"
    }).formatToParts(date);
    const values = Object.fromEntries(
      parts.map(part => [part.type, part.value])
    );
    return `${values.year}-${values.month}-${values.day}`;
  }
  // Stable hash: all visitors on the same local calendar day
  // receive the same curated passage.
  function hashString(value) {
    let hash = 2166136261;
    for (let i = 0; i < value.length; i++) {
      hash ^= value.charCodeAt(i);
      hash = Math.imul(hash, 16777619);
    }
    return hash >>> 0;
  }
  // Determine the passage for a specific date.
  function getPassageForDate(dateKey) {
    return passages[hashString(dateKey) % passages.length];
  }
  // Extract Bible verses.
  function extractVerses(data) {
    const chapters = Object.values(data || {});
    const found = [];
    for (const chapter of chapters) {
      if (chapter && Array.isArray(chapter.verses)) {
        found.push(...chapter.verses);
      }
    }
    return found.sort((a, b) =>
      (a.chapter - b.chapter) || (a.verse - b.verse)
    );
  }
  // Prevent overlapping API requests.
  let requestController = null;
  let requestId = 0;
  // Show the daily Bible passage.
  async function showDailyVerse() {
    const dateKey = localDateKey();
    const selected = getPassageForDate(dateKey);
    // const cacheKey = `sv-dagtekst ${dateKey} (${selected.label})`;
    const cacheKey = `sv-dagtekst`;
    // Cancel any previous request.
    if (requestController) {
      requestController.abort();
    }
    requestController = new AbortController();
    const currentRequestId = ++requestId;
    textEl.textContent = "De Bijbeltekst wordt geladen…";
    refEl.textContent = "";
    statusEl.textContent = "";
    try {
      let verses = null;
      // Try to retrieve the cached passage.
      try {
        const cached = localStorage.getItem(cacheKey);
        if (cached) {
          verses = JSON.parse(cached);
        }
      } catch (_) {
        // Continue without cache if storage is unavailable.
      }
      // Fetch the passage if no valid cache exists.
      if (!Array.isArray(verses) || !verses.length) {
        const url = API + encodeURIComponent(selected.ref);
        const response = await fetch(url, {
          headers: {
            "Accept": "application/json"
          },
          signal: requestController.signal
        });
        if (!response.ok) {
          throw new Error(`Bijbel-API: ${response.status}`);
        }
        const data = await response.json();
        verses = extractVerses(data);
        if (!verses.length) {
          throw new Error("Bijbel-API: Geen verzen gevonden voor " + selected.ref);
        }
        // Cache the retrieved verses.
        try {
          localStorage.setItem(cacheKey, JSON.stringify(verses));
        } catch (_) {
          // Continue without cache if storage is unavailable.
        }
      }
      // Ignore outdated requests or results from a previous day.
      if (currentRequestId !== requestId || dateKey !== localDateKey()) {
        return;
      }
      // Display the passage.
      textEl.textContent = verses
        .map(v => v.text)
        .filter(Boolean)
        .join(" ");
      refEl.textContent = selected.label;
      statusEl.textContent = "";
    } catch (error) {
      // Ignore intentionally cancelled requests.
      if (error.name === "AbortError") {
        return;
      }
      // Ignore errors from outdated requests.
      if (currentRequestId !== requestId) {
        return;
      }
      console.error("SV DAGTEKST:", error);
      textEl.textContent = "De Bijbeltekst kon momenteel niet worden geladen.";
      refEl.textContent = selected.label;
      statusEl.textContent = "Controleer de verbinding of probeer het later opnieuw.";
    }
  }
  // Calculate the next midnight in Europe/Amsterdam.
  function getNextAmsterdamMidnight() {
    const now = new Date();
    const dateKey = localDateKey(now);
    const [year, month, day] = dateKey.split("-").map(Number);
    const nextDate = new Date(Date.UTC(year, month - 1, day + 1));
    const target = Date.UTC(
      nextDate.getUTCFullYear(),
      nextDate.getUTCMonth(),
      nextDate.getUTCDate()
    );
    const formatter = new Intl.DateTimeFormat("en-GB", {
      timeZone: "Europe/Amsterdam",
      year: "numeric",
      month: "2-digit",
      day: "2-digit",
      hour: "2-digit",
      minute: "2-digit",
      second: "2-digit",
      hourCycle: "h23"
    });
    let timestamp = target;
    // Resolve the Amsterdam UTC offset, including DST.
    for (let i = 0; i < 3; i++) {
      const parts = Object.fromEntries(
        formatter.formatToParts(new Date(timestamp))
          .map(part => [part.type, part.value])
      );
      const localAsUTC = Date.UTC(
        Number(parts.year),
        Number(parts.month) - 1,
        Number(parts.day),
        Number(parts.hour),
        Number(parts.minute),
        Number(parts.second)
      );
      const offset = localAsUTC - timestamp;
      timestamp = target - offset;
    }
    return new Date(timestamp);
  }
  // Schedule the next update at Amsterdam midnight.
  function startDailyCheck() {
    let midnightTimer;
    function refreshAndSchedule() {
      clearTimeout(midnightTimer);
      // Update the passage.
      showDailyVerse();
      // Calculate the next Amsterdam midnight.
      const nextMidnight = getNextAmsterdamMidnight();
      const delay = nextMidnight.getTime() - Date.now();
      midnightTimer = setTimeout(
        refreshAndSchedule,
        Math.max(1000, delay)
      );
    }
    // Initial update.
    refreshAndSchedule();
    // Recheck when the visitor returns to the page.
    document.addEventListener("visibilitychange", () => {
      if (!document.hidden) {
        refreshAndSchedule();
      }
    });
  }
  // Start the daily Bible passage.
  startDailyCheck();
